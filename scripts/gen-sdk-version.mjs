#!/usr/bin/env node
//
// Stamp `@uptimizr/sdk-core`'s package version into its source.
//
// `SDK_VERSION` is written onto every event's envelope as `sdkVersion`, so it has
// to match the package that shipped it. It cannot be read at runtime the way the
// collector and the MCP server read theirs: sdk-core runs in the browser, with no
// `node:module` to reach `package.json`, and importing the manifest as JSON would
// bundle all of it into every connector. So this script projects the one field
// into
//
//   oss/packages/sdk-core/src/version.ts
//
// as a plain constant. `pnpm version:packages` runs it straight after
// `changeset version`, so the Version Packages PR carries the bump and the
// constant together. Never edit the generated file.
//
// Run locally:    pnpm gen:version
// Staleness gate: pnpm gen:version:check   (exits non-zero when the committed
//                 constant drifted from `package.json`)

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import process from "node:process";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const PACKAGE_JSON = "oss/packages/sdk-core/package.json";
/** The module this script owns, relative to the repo root. */
const OUTPUT = "oss/packages/sdk-core/src/version.ts";

const { version } = JSON.parse(await readFile(path.join(ROOT, PACKAGE_JSON), "utf8"));
if (typeof version !== "string" || version.length === 0) {
  throw new Error(`${PACKAGE_JSON} declares no version`);
}

const rendered = `// Generated by scripts/gen-sdk-version.mjs from package.json. Do not edit: run \`pnpm gen:version\`.

/** Version of this SDK, stamped onto every event's envelope as \`sdkVersion\`. */
export const SDK_VERSION = ${JSON.stringify(version)};
`;

const target = path.join(ROOT, OUTPUT);
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => null);
  if (current?.replaceAll("\r\n", "\n") !== rendered) {
    console.error(`${OUTPUT} is out of date with ${PACKAGE_JSON}. Run \`pnpm gen:version\`.`);
    process.exit(1);
  }
} else {
  await writeFile(target, rendered);
}
